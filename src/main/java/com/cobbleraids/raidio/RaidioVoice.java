package com.cobbleraids.raidio;

/**
 * The four channels Raidio is played on, like a Game Boy's: a square-wave lead (the tune), a second pulse (harmony and sparkle), a bass, and a noise tick for
 * static. Each is a vanilla note-block instrument, so no resource pack or client mod is needed. No Minecraft types.
 */
public enum RaidioVoice {
    BIT, PLING, BASS, HAT
}
