package com.cobbleraids.item;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import java.awt.image.BufferedImage;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import javax.imageio.ImageIO;
import org.junit.jupiter.api.Test;

/** The Raidio item's art: a model and a texture generated by tools/raidio/make_raidio_item.py. A model can be silently wrong, so what it points at is checked. */
class RaidioItemArtTest {
    private static final String PATH = "/assets/cobbleraids/";

    private static JsonObject model() throws IOException {
        try (InputStream in = RaidioItemArtTest.class.getResourceAsStream(PATH + "models/item/" + RaidRadarItem.MODEL_PATH + ".json")) {
            assertNotNull(in, "the Raidio model is missing from the jar");
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonObject();
        }
    }

    private static BufferedImage texture() throws IOException {
        try (InputStream in = RaidioItemArtTest.class.getResourceAsStream(PATH + "textures/item/" + RaidRadarItem.MODEL_PATH + ".png")) {
            assertNotNull(in, "the Raidio texture is missing from the jar");
            return ImageIO.read(in);
        }
    }

    @Test
    void theModelAndTextureAreShippedInThePack() {
        assertTrue(RaidItemPack.NAMES.contains(RaidRadarItem.MODEL_PATH), "RaidItemPack must add the Raidio art to the resource pack");
    }

    @Test
    void theModelPointsAtTheTexture() throws IOException {
        assertEquals("cobbleraids:item/" + RaidRadarItem.MODEL_PATH, model().getAsJsonObject("textures").get("all").getAsString());
        BufferedImage texture = texture();
        assertEquals(texture.getWidth(), texture.getHeight(), "a square atlas keeps the 0 to 16 uv space the same on both axes");
    }

    @Test
    void theModelDoesNotRelyOnTextureSizeWhichMinecraftIgnores() throws IOException {
        assertTrue(!model().has("texture_size"), "vanilla Minecraft ignores texture_size and reads uv in a 0 to 16 space; a model that needs it is drawn wrongly");
    }

    @Test
    void everyFaceSamplesRealOpaquePixelsInsideTheTexture() throws IOException {
        JsonObject model = model();
        BufferedImage texture = texture();
        int faces = 0;
        for (JsonElement element : model.getAsJsonArray("elements")) {
            JsonObject box = element.getAsJsonObject();
            String name = box.has("name") ? box.get("name").getAsString() : "element";
            for (var entry : box.getAsJsonObject("faces").entrySet()) {
                // Minecraft reads uv in a 0 to 16 space whatever the texture's resolution, so a pixel is uv * size / 16.
                JsonArray uv = entry.getValue().getAsJsonObject().getAsJsonArray("uv");
                double kx = texture.getWidth() / 16.0, ky = texture.getHeight() / 16.0;
                int x0 = (int) Math.round(uv.get(0).getAsDouble() * kx), y0 = (int) Math.round(uv.get(1).getAsDouble() * ky);
                int x1 = (int) Math.round(uv.get(2).getAsDouble() * kx), y1 = (int) Math.round(uv.get(3).getAsDouble() * ky);
                for (int i = 0; i < 4; i++) {
                    double inPixels = uv.get(i).getAsDouble() * (i % 2 == 0 ? kx : ky);
                    assertTrue(Math.abs(inPixels - Math.round(inPixels)) < 1e-6, name + " " + entry.getKey() + " uv does not land on whole pixels: " + uv);
                }
                String where = name + " " + entry.getKey();
                assertTrue(x0 >= 0 && y0 >= 0 && x1 <= texture.getWidth() && y1 <= texture.getHeight(), where + " samples outside the texture");
                assertTrue(x1 > x0 && y1 > y0, where + " samples nothing");
                for (int y = y0; y < y1; y++) {
                    for (int x = x0; x < x1; x++) {
                        assertEquals(255, texture.getRGB(x, y) >>> 24, where + " samples a transparent pixel at " + x + "," + y);
                    }
                }
                faces++;
            }
        }
        assertTrue(faces >= 6, "the model should have faces to draw, found " + faces);
    }

    @Test
    void everyBoxIsInsideWhatTheGameWillRenderAndHasSize() throws IOException {
        for (JsonElement element : model().getAsJsonArray("elements")) {
            JsonObject box = element.getAsJsonObject();
            JsonArray from = box.getAsJsonArray("from"), to = box.getAsJsonArray("to");
            for (int i = 0; i < 3; i++) {
                assertTrue(from.get(i).getAsDouble() >= -16 && to.get(i).getAsDouble() <= 32, "a box is outside the -16 to 32 range the game renders");
                assertTrue(to.get(i).getAsDouble() > from.get(i).getAsDouble(), "a box has no thickness on axis " + i);
            }
            if (box.has("rotation")) {
                double angle = box.getAsJsonObject("rotation").get("angle").getAsDouble();
                assertTrue(Math.abs(angle) <= 45 && angle % 22.5 == 0, "the game only allows 22.5 degree steps up to 45, found " + angle);
            }
        }
    }

    @Test
    void everyHandAndInventoryViewIsDefined() throws IOException {
        JsonObject display = model().getAsJsonObject("display");
        for (String view : new String[] {"gui", "ground", "fixed", "thirdperson_righthand", "thirdperson_lefthand", "firstperson_righthand", "firstperson_lefthand"}) {
            assertTrue(display.has(view), "no " + view + " transform: the item would draw at the default size and angle there");
        }
    }
}
