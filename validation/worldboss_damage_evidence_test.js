'use strict';
const assert = require('assert');
const {Conditions} = require('../src/main/resources/assets/cobbleraids/showdown/mods/conditions.js');
const messages = [];
const battle = {turn: 1, add: (...args) => messages.push(args)};
const target = {side: {battle: {gameType: 'raid'}}};
const source = {name: 'player'};
assert.strictEqual(Conditions.raidboss.onDamage.call(battle, 10, target, source), 0);
assert.strictEqual(Conditions.raidboss.onDamage.call(battle, 5, target, source), 0);
battle.turn = 2;
assert.strictEqual(Conditions.raidboss.onDamage.call(battle, 3, target, undefined), 0);
assert.deepStrictEqual(messages.map(parts => parts.slice(3)), [[source, 1, 1], [source, 1, 2], ['', 2, 3]]);
assert.strictEqual(target.__cobbleRaidsSuppressVanillaDamageLog, true);
const otherMessages = [];
Conditions.raidboss.onDamage.call({turn: 1, add: (...args) => otherMessages.push(args)}, 1, target, source);
assert.strictEqual(otherMessages[0][5], 1, 'Sequence origins are battle-local');
const normal = {side: {battle: {gameType: 'singles'}}};
assert.strictEqual(Conditions.raidboss.onDamage.call(battle, 17, normal, source), 17);
assert.strictEqual(messages.length, 3, 'Non-raid combat remains untouched');
console.log('World Boss authoritative turn/sequence emission: PASS');
